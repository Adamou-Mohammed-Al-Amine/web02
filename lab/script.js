/* ═══════════════════════════════════════════════════════════
   LANGUAGE SYSTEM
═══════════════════════════════════════════════════════════ */
let currentLang = localStorage.getItem('amine_lang') || 'en';

function setLang(lang) {
  currentLang = lang;
  localStorage.setItem('amine_lang', lang);

  const html = document.documentElement;
  html.setAttribute('lang', lang);
  html.setAttribute('dir', lang === 'ar' ? 'rtl' : 'ltr');

  // Update all data-i18n elements
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (TRANSLATIONS[lang] && TRANSLATIONS[lang][key]) {
      el.textContent = TRANSLATIONS[lang][key];
    }
  });

  // Update placeholder attributes
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const key = el.getAttribute('data-i18n-ph');
    if (TRANSLATIONS[lang] && TRANSLATIONS[lang][key]) {
      el.setAttribute('placeholder', TRANSLATIONS[lang][key]);
    }
  });

  // Update select options
  const cfType = document.getElementById('cfType');
  if (cfType) {
    const optKeys = ['form_type_ph','form_opt1','form_opt2','form_opt3','form_opt4','form_opt5'];
    cfType.querySelectorAll('option').forEach((opt, i) => {
      if (TRANSLATIONS[lang][optKeys[i]]) {
        opt.textContent = TRANSLATIONS[lang][optKeys[i]];
      }
    });
  }

  // Update lang buttons
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
  });

  // RTL adjustments for marquee
  const mTrack = document.getElementById('marqueeTrack');
  if (mTrack) {
    mTrack.style.animationDirection = lang === 'ar' ? 'reverse' : 'normal';
  }
}

window.setLang = setLang;

/* ═══════════════════════════════════════════════════════════
   LOADER
═══════════════════════════════════════════════════════════ */
(function initLoader() {
  let pct = 0;
  const pctEl = document.getElementById('loaderPct');
  const loader = document.getElementById('loader');

  const interval = setInterval(() => {
    pct = Math.min(pct + Math.random() * 20, 100);
    if (pctEl) pctEl.textContent = Math.floor(pct) + '%';
    if (pct >= 100) {
      clearInterval(interval);
      setTimeout(() => {
        if (loader) loader.classList.add('hide');
      }, 350);
    }
  }, 100);
})();

/* ═══════════════════════════════════════════════════════════
   CURSOR
═══════════════════════════════════════════════════════════ */
(function initCursor() {
  const dot  = document.getElementById('cursor-dot');
  const ring = document.getElementById('cursor-ring');
  if (!dot || !ring) return;

  let mx = 0, my = 0, rx = 0, ry = 0;

  document.addEventListener('mousemove', e => {
    mx = e.clientX; my = e.clientY;
    dot.style.left = mx + 'px';
    dot.style.top  = my + 'px';
  });

  (function animRing() {
    rx += (mx - rx) * 0.13;
    ry += (my - ry) * 0.13;
    ring.style.left = rx + 'px';
    ring.style.top  = ry + 'px';
    requestAnimationFrame(animRing);
  })();

  document.querySelectorAll('a, button, .yt-card, .short-card, .service-card, .why-card').forEach(el => {
    el.addEventListener('mouseenter', () => document.body.classList.add('cursor-hover'));
    el.addEventListener('mouseleave', () => document.body.classList.remove('cursor-hover'));
  });
})();

/* ═══════════════════════════════════════════════════════════
   SCROLL PROGRESS
═══════════════════════════════════════════════════════════ */
window.addEventListener('scroll', () => {
  const prog = document.getElementById('scroll-progress');
  if (prog) {
    const pct = window.scrollY / (document.body.scrollHeight - window.innerHeight);
    prog.style.width = (pct * 100) + '%';
  }
});

/* ═══════════════════════════════════════════════════════════
   NAVBAR
═══════════════════════════════════════════════════════════ */
(function initNavbar() {
  const navbar = document.getElementById('navbar');
  if (!navbar) return;

  window.addEventListener('scroll', () => {
    navbar.classList.toggle('scrolled', window.scrollY > 60);
    highlightActiveNav();
  });

  // Hamburger
  const hamburger = document.getElementById('hamburger');
  const mobileMenu = document.getElementById('mobileMenu');
  const mobileClose = document.getElementById('mobileClose');

  if (hamburger && mobileMenu) {
    hamburger.addEventListener('click', () => mobileMenu.classList.add('open'));
  }
  if (mobileClose && mobileMenu) {
    mobileClose.addEventListener('click', () => mobileMenu.classList.remove('open'));
  }

  // Lang switcher buttons (desktop)
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', () => setLang(btn.getAttribute('data-lang')));
  });
})();

window.closeMobileMenu = function () {
  const m = document.getElementById('mobileMenu');
  if (m) m.classList.remove('open');
};

/* ═══════════════════════════════════════════════════════════
   ACTIVE NAV HIGHLIGHT
═══════════════════════════════════════════════════════════ */
function highlightActiveNav() {
  const sections = document.querySelectorAll('section[id], footer[id]');
  let current = '';
  sections.forEach(sec => {
    if (window.scrollY >= sec.offsetTop - 140) current = sec.id;
  });
  document.querySelectorAll('.nav-links a').forEach(a => {
    a.classList.toggle('active', a.getAttribute('href') === '#' + current);
  });
}

