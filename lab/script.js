/* ═══════════════════════════════════════════════════════════
   SMOOTH COUNTER ANIMATION FOR STAT CARDS
═══════════════════════════════════════════════════════════ */
(function initCounters() {
  const observer = new IntersectionObserver(entries => {
    entries.forEach(entry => {
      if (!entry.isIntersecting) return;
      const el = entry.target;
      const numEl = el.querySelector('.stat-num');
      if (!numEl || numEl.dataset.counted) return;
      numEl.dataset.counted = 'true';

      const text = numEl.textContent.trim();
      const match = text.match(/^(\d+)/);
      if (!match) return;

      const target = parseInt(match[1]);
      const suffix = text.replace(match[1], '');
      const dur = 1800;
      const start = performance.now();

      function update(now) {
        const progress = Math.min((now - start) / dur, 1);
        const eased = 1 - Math.pow(1 - progress, 3);
        numEl.textContent = Math.round(eased * target) + suffix;
        if (progress < 1) requestAnimationFrame(update);
      }
      requestAnimationFrame(update);
      observer.unobserve(el);
    });
  }, { threshold: 0.5 });

  document.querySelectorAll('.stat-card').forEach(el => observer.observe(el));
})();

